# FORMAT SPECIFIERS
# format specifiers format a value based on what flags are inserted
# SYNTAX : {value:flags}

#.(number)f = round to that many decimal places (fixed point)
#:(number)  = allocate that many spaces
#:03 = allocate and zero pad that many spaces
#:< = left justify
#:> = right justify
#:^ = center align
#:+ = use a plus sign to indicate a positive value
#:= = place sign to leftmost position
#:  = insert a space before positive numbers
#:, = comma seperator

price1 = 3.1456378
price2 = -38747.738
price3 = 12348.3736


#-----------------------------------------------------------------------------------------------------------------------------------------------
# decimal point {: .numberf}
#-----------------------------------------------------------------------------------------------------------------------------------------------

print(f" Price 1 is : {price1 : .2f}")
print(f" Price 2 is : {price2 : .2f}")
print(f" Price 3 is : {price3 : .2f}")

#-----------------------------------------------------------------------------------------------------------------------------------------------
# space {: number}
#-----------------------------------------------------------------------------------------------------------------------------------------------

print(f" Price 1 is : {price1 : 28}")
print(f" Price 2 is : {price2 : 28}")
print(f" Price 3 is : {price3 : 28}")

#-----------------------------------------------------------------------------------------------------------------------------------------------
# zero padded and space {: 0number}
#-----------------------------------------------------------------------------------------------------------------------------------------------

print(f" Price 1 is : {price1 : 028}")
print(f" Price 2 is : {price2 : 029}")
print(f" Price 3 is : {price3 : 028}")

#-----------------------------------------------------------------------------------------------------------------------------------------------
# left justify {: <number}
#-----------------------------------------------------------------------------------------------------------------------------------------------

print(f" Price 1 is : {price1 : <28}")
print(f" Price 2 is : {price2 : <28}")
print(f" Price 3 is : {price3 : <28}")

#-----------------------------------------------------------------------------------------------------------------------------------------------
# right justify {: >number}
#-----------------------------------------------------------------------------------------------------------------------------------------------

print(f" Price 1 is : {price1 : >28}")
print(f" Price 2 is : {price2 : >28}")
print(f" Price 3 is : {price3 : >28}")


#-----------------------------------------------------------------------------------------------------------------------------------------------
# center justify {: ^number}
#-----------------------------------------------------------------------------------------------------------------------------------------------

print(f" Price 1 is : {price1 : ^28}")
print(f" Price 2 is : {price2 : ^28}")
print(f" Price 3 is : {price3 : ^28}")


#-----------------------------------------------------------------------------------------------------------------------------------------------
# plus sign {:+}
#-----------------------------------------------------------------------------------------------------------------------------------------------

print(f" Price 1 is : {price1 :+}")
print(f" Price 2 is : {price2 :+}")
print(f" Price 3 is : {price3 :+}")


#-----------------------------------------------------------------------------------------------------------------------------------------------
# thousand separator justify {: <number}
#-----------------------------------------------------------------------------------------------------------------------------------------------

print(f" Price 1 is : {price1 : ,}")
print(f" Price 2 is : {price2 : ,}")
print(f" Price 3 is : {price3 : ,}")

#-----------------------------------------------------------------------------------------------------------------------------------------------

