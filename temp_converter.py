# Here we will write a code to convert the temperature from degree celcius to fahrenheit
# formula : F = 9/5 * C + 32

temp_in_celcius = float(input("Enter the temperature in degree Celcius : "))

temp_in_fahrenheit = ((9/5) * temp_in_celcius) + 32

print(f" The conversion of {temp_in_celcius} degree celcius to Fahrenheit is {temp_in_fahrenheit} Fahrenheit ")

